name = "ada lovelace"
print(name.title())

#точка после переменной (name) заставляет применить метод title() к этой переменной. title() преобразует все слова в таком формате (Ада Ловлас)#
#учитывая, что вводные данные могут быть разные (АДА ЛОВЛАС, Ада ловлас etc.)

print(name.upper()) #преобразование переменной в нижний регистр#
print(name.lower()) #преобразование переменной в верхний регистр#
